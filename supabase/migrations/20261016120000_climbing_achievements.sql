-- Adds net elevation supplied by the app and the Escalador achievement.
-- A climbing journey has destination elevation minus origin elevation > 50 m.
alter table public.trips
  add column if not exists net_elevation_meters double precision;

create or replace function public.upsert_own_trips(p_trips jsonb)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_count integer := 0;
begin
  if v_user_id is null then
    raise exception 'authentication_required';
  end if;
  if jsonb_typeof(p_trips) <> 'array' then
    raise exception 'invalid_trip_payload';
  end if;

  insert into public.trips as existing (
    user_id,
    provider,
    source_trip_id,
    origin_station_id,
    origin_station_name,
    destination_station_id,
    destination_station_name,
    started_at,
    duration_seconds,
    origin_latitude,
    origin_longitude,
    destination_latitude,
    destination_longitude,
    direct_distance_meters,
    net_elevation_meters,
    bike_id,
    trip_cost
  )
  select
    v_user_id,
    r.provider,
    r.source_trip_id,
    r.origin_station_id,
    r.origin_station_name,
    r.destination_station_id,
    r.destination_station_name,
    r.started_at,
    r.duration_seconds,
    r.origin_latitude,
    r.origin_longitude,
    r.destination_latitude,
    r.destination_longitude,
    r.direct_distance_meters,
    r.net_elevation_meters,
    r.bike_id,
    r.trip_cost
  from jsonb_to_recordset(p_trips) as r(
    provider text,
    source_trip_id text,
    origin_station_id text,
    origin_station_name text,
    destination_station_id text,
    destination_station_name text,
    started_at timestamptz,
    duration_seconds integer,
    origin_latitude double precision,
    origin_longitude double precision,
    destination_latitude double precision,
    destination_longitude double precision,
    direct_distance_meters double precision,
    net_elevation_meters double precision,
    bike_id text,
    trip_cost numeric
  )
  where r.provider = 'bicimad'
    and nullif(r.source_trip_id, '') is not null
    and r.duration_seconds > 0
  on conflict (user_id, provider, source_trip_id) do update set
    origin_station_id = coalesce(excluded.origin_station_id, existing.origin_station_id),
    origin_station_name = coalesce(excluded.origin_station_name, existing.origin_station_name),
    destination_station_id = coalesce(excluded.destination_station_id, existing.destination_station_id),
    destination_station_name = coalesce(excluded.destination_station_name, existing.destination_station_name),
    started_at = coalesce(excluded.started_at, existing.started_at),
    duration_seconds = coalesce(excluded.duration_seconds, existing.duration_seconds),
    origin_latitude = coalesce(excluded.origin_latitude, existing.origin_latitude),
    origin_longitude = coalesce(excluded.origin_longitude, existing.origin_longitude),
    destination_latitude = coalesce(excluded.destination_latitude, existing.destination_latitude),
    destination_longitude = coalesce(excluded.destination_longitude, existing.destination_longitude),
    direct_distance_meters = coalesce(excluded.direct_distance_meters, existing.direct_distance_meters),
    net_elevation_meters = coalesce(excluded.net_elevation_meters, existing.net_elevation_meters),
    bike_id = coalesce(excluded.bike_id, existing.bike_id),
    trip_cost = coalesce(excluded.trip_cost, existing.trip_cost);

  get diagnostics v_count = row_count;
  perform public.refresh_profile_stats(v_user_id);
  return v_count;
end;
$$;

revoke all on function public.upsert_own_trips(jsonb)
  from public, anon, authenticated;
grant execute on function public.upsert_own_trips(jsonb) to authenticated;

alter function public.refresh_profile_achievement_levels(uuid)
  rename to refresh_profile_levels_before_climbing;

create or replace function public.refresh_profile_climbing_achievement(
  p_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  stage record;
  has_current boolean := false;
  current_ended_at timestamptz;
  current_origin_id text;
  current_destination_id text;
  current_net_elevation double precision := 0;
  current_elevation_complete boolean := true;
  climbing_progress integer := 0;
begin
  create temporary table if not exists achievement_climbing_events (
    event_index bigint generated by default as identity,
    ended_at timestamptz not null
  ) on commit drop;
  truncate table pg_temp.achievement_climbing_events;

  for stage in
    select
      trip.id,
      trip.origin_station_id,
      trip.destination_station_id,
      trip.started_at,
      trip.started_at + trip.duration_seconds * interval '1 second' as ended_at,
      trip.net_elevation_meters
    from public.trips trip
    where trip.user_id = p_user_id
      and trip.duration_seconds > 0
      and trip.origin_station_id <> trip.destination_station_id
    order by trip.started_at, trip.id
  loop
    if not has_current then
      has_current := true;
      current_origin_id := stage.origin_station_id;
      current_destination_id := stage.destination_station_id;
      current_ended_at := stage.ended_at;
      current_elevation_complete := stage.net_elevation_meters is not null;
      current_net_elevation := coalesce(stage.net_elevation_meters, 0);
    elsif extract(epoch from stage.started_at - current_ended_at) between 0 and 119
      and current_destination_id = stage.origin_station_id
      and current_origin_id <> stage.destination_station_id then
      current_destination_id := stage.destination_station_id;
      current_ended_at := stage.ended_at;
      current_elevation_complete := current_elevation_complete
        and stage.net_elevation_meters is not null;
      current_net_elevation := current_net_elevation
        + coalesce(stage.net_elevation_meters, 0);
    else
      if current_elevation_complete and current_net_elevation > 50.0 then
        insert into pg_temp.achievement_climbing_events (ended_at)
        values (current_ended_at);
      end if;
      current_origin_id := stage.origin_station_id;
      current_destination_id := stage.destination_station_id;
      current_ended_at := stage.ended_at;
      current_elevation_complete := stage.net_elevation_meters is not null;
      current_net_elevation := coalesce(stage.net_elevation_meters, 0);
    end if;
  end loop;

  if has_current
    and current_elevation_complete
    and current_net_elevation > 50.0 then
    insert into pg_temp.achievement_climbing_events (ended_at)
    values (current_ended_at);
  end if;

  select count(*)::integer
    into climbing_progress
  from pg_temp.achievement_climbing_events;

  insert into public.user_achievements (
    user_id,
    category_id,
    level_id,
    threshold,
    progress,
    unlocked_at,
    updated_at
  )
  select
    p_user_id,
    'climbing_trips_50_m',
    level.level_id,
    level.threshold,
    climbing_progress,
    min(event.ended_at),
    now()
  from (values
    ('graphite', 1),
    ('bronze', 10),
    ('silver', 50),
    ('gold', 100)
  ) as level(level_id, threshold)
  join (
    select
      climbing.ended_at,
      row_number() over (order by climbing.event_index) as progress_value
    from pg_temp.achievement_climbing_events climbing
  ) event on event.progress_value >= level.threshold
  group by level.level_id, level.threshold
  on conflict (user_id, category_id, level_id) do update set
    threshold = excluded.threshold,
    progress = greatest(excluded.progress, excluded.threshold),
    unlocked_at = least(
      public.user_achievements.unlocked_at,
      excluded.unlocked_at
    ),
    updated_at = now();

  update public.user_achievements achievement
  set progress = greatest(climbing_progress, achievement.threshold),
      updated_at = now()
  where achievement.user_id = p_user_id
    and achievement.category_id = 'climbing_trips_50_m';
end;
$$;

create or replace function public.refresh_profile_achievement_levels(
  p_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.refresh_profile_levels_before_climbing(p_user_id);
  perform public.refresh_profile_climbing_achievement(p_user_id);
end;
$$;

revoke all on function public.refresh_profile_levels_before_climbing(uuid)
  from public, anon, authenticated;
revoke all on function public.refresh_profile_climbing_achievement(uuid)
  from public, anon, authenticated;
revoke all on function public.refresh_profile_achievement_levels(uuid)
  from public, anon, authenticated;

do $$
declare
  existing_profile record;
begin
  for existing_profile in select profile.user_id from public.profiles profile loop
    perform public.refresh_profile_achievements(existing_profile.user_id);
  end loop;
end;
$$;
